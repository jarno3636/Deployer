import fs from 'node:fs';
import path from 'node:path';
import solc from 'solc';

const root=process.cwd();
const sourcePath='contracts/IndexioMultiAssetPayRouter_V2.sol';
const code=fs.readFileSync(path.join(root,sourcePath),'utf8');
const settings={optimizer:{enabled:true,runs:200},evmVersion:'cancun',outputSelection:{'*':{'*':['abi','evm.bytecode.object','evm.deployedBytecode.object','metadata']}}};
const input={language:'Solidity',sources:{[sourcePath]:{content:code}},settings};
const result=JSON.parse(solc.compile(JSON.stringify(input)));
for(const e of result.errors||[]){(e.severity==='error'?console.error:console.warn)(e.formattedMessage||e.message)}
if((result.errors||[]).some(e=>e.severity==='error'))process.exit(1);
const artifact=result.contracts?.[sourcePath]?.IndexioMultiAssetPayRouterV2;
if(!artifact?.abi||!artifact.evm?.bytecode?.object)throw Error('V2 Pay compilation missing deployment artifact');
const size=artifact.evm.deployedBytecode.object.length/2;
if(size>=24576)throw Error(`V2 Pay exceeds 24KB maximum (${size})`);
const version=solc.version().match(/^\d+\.\d+\.\d+\+commit\.[a-f0-9]+/)?.[0];
if(!version)throw Error('Could not resolve compiler version');
fs.mkdirSync(path.join(root,'lib'),{recursive:true});
fs.mkdirSync(path.join(root,'artifacts'),{recursive:true});
const head='// AUTOGENERATED by scripts/compile-indexio-pay-v2.mjs - do not edit.\n';
fs.writeFileSync(path.join(root,'lib/indexio-pay-v2.generated.ts'),head+
  `export const payV2Abi=${JSON.stringify(artifact.abi)} as const;\n`+
  `export const payV2Bytecode=${JSON.stringify('0x'+artifact.evm.bytecode.object)} as \`0x\${string}\`;\n`+
  `export const payV2Compiler=${JSON.stringify('v'+version)} as const;\n`);
fs.writeFileSync(path.join(root,'artifacts/indexio-pay-v2-standard-json-input.json'),JSON.stringify(input,null,2));
fs.writeFileSync(path.join(root,'artifacts/indexio-pay-v2-contract.json'),JSON.stringify({contract:sourcePath+':IndexioMultiAssetPayRouterV2',compiler:'v'+version,abi:artifact.abi,bytecode:'0x'+artifact.evm.bytecode.object,optimizerRuns:200,evmVersion:'cancun'},null,2));
console.log(`Multi-asset Pay V2 compiled: ${size} runtime bytes / ${version}`);
