import fs from 'fs';
import path from 'path';
import solc from 'solc';
import { createRequire } from 'module';

const require = createRequire(import.meta.url);

const ROOT = process.cwd();

const CONTRACT_PATH = path.join(
  ROOT,
  'contracts',
  'AiStocksIndexLaunchV1.sol',
);

const OUTPUT_PATH = path.join(
  ROOT,
  'lib',
  'marketplace.generated.ts',
);

const SOURCE_KEY =
  'contracts/AiStocksIndexLaunchV1.sol';

const CONTRACT_NAMES = [
  'AiStocksAssetRegistryV1',
  'AiStocksPolicyManagerV1',
  'AiStocksIndexFactoryV1',
  'AiStocksIndexMintRouterV1',
  'AiStocksIndexRedeemRouterV1',
];

function readFile(filePath) {
  return fs.readFileSync(filePath, 'utf8');
}

function resolveImport(importPath) {
  try {
    if (importPath.startsWith('@')) {
      return require.resolve(importPath, {
        paths: [ROOT],
      });
    }

    return path.resolve(
      path.dirname(CONTRACT_PATH),
      importPath,
    );
  } catch {
    return null;
  }
}

function findImports(importPath) {
  const resolved =
    resolveImport(importPath);

  if (!resolved) {
    return {
      error: `Could not resolve import: ${importPath}`,
    };
  }

  try {
    return {
      contents: readFile(resolved),
    };
  } catch {
    return {
      error: `Could not read import: ${importPath}`,
    };
  }
}

function collectSources(
  sourceKey,
  sourceContents,
  collected = {},
) {
  if (collected[sourceKey]) {
    return collected;
  }

  collected[sourceKey] = {
    content: sourceContents,
  };

  const importRegex =
    /import\s+(?:(?:[^'"]*from\s*)?)["']([^"']+)["'];/g;

  let match;

  while (
    (match =
      importRegex.exec(
        sourceContents,
      ))
  ) {
    const importPath =
      match[1];

    const resolved =
      resolveImport(importPath);

    if (!resolved) {
      throw new Error(
        `Unable to resolve ${importPath}`,
      );
    }

    const importedSource =
      readFile(resolved);

    collectSources(
      importPath,
      importedSource,
      collected,
    );
  }

  return collected;
}

const mainSource =
  readFile(CONTRACT_PATH);

const sources =
  collectSources(
    SOURCE_KEY,
    mainSource,
  );

const input = {
  language: 'Solidity',

  sources,

  settings: {
    viaIR: true,

    optimizer: {
      enabled: true,
      runs: 200,
    },

    outputSelection: {
      '*': {
        '*': [
          'abi',
          'evm.bytecode.object',
          'evm.deployedBytecode.object',
        ],
      },
    },
  },
};

const output =
  JSON.parse(
    solc.compile(
      JSON.stringify(input),
      {
        import: findImports,
      },
    ),
  );

if (output.errors) {
  for (const error of output.errors) {
    console.log(
      error.formattedMessage,
    );
  }

  const fatal =
    output.errors.filter(
      (error) =>
        error.severity ===
        'error',
    );

  if (fatal.length) {
    process.exit(1);
  }
}

const compiled =
  output.contracts?.[
    SOURCE_KEY
  ];

if (!compiled) {
  throw new Error(
    'No compiled contracts found.',
  );
}

const artifacts = {};

for (
  const contractName of
  CONTRACT_NAMES
) {
  const contract =
    compiled[contractName];

  if (!contract) {
    throw new Error(
      `Missing compiled contract: ${contractName}`,
    );
  }

  const bytecodeObject =
    contract.evm?.bytecode
      ?.object;

  if (!bytecodeObject) {
    throw new Error(
      `Missing bytecode for ${contractName}`,
    );
  }

  artifacts[contractName] = {
    abi: contract.abi,

    bytecode:
      `0x${bytecodeObject}`,
  };
}

const compilerVersion =
  solc.version();

const generated =
`// AUTO-GENERATED FILE.
// DO NOT EDIT MANUALLY.
// Generated by scripts/compile-contract.mjs

export const compilerVersion = ${JSON.stringify(
  compilerVersion,
)} as const;

export const verificationInput = ${JSON.stringify(
  JSON.stringify(input),
)} as const;

export const contractArtifacts = ${JSON.stringify(
  artifacts,
  null,
  2,
)} as const;
`;

fs.mkdirSync(
  path.dirname(OUTPUT_PATH),
  {
    recursive: true,
  },
);

fs.writeFileSync(
  OUTPUT_PATH,
  generated,
);

console.log(
  `Compiled AiStocks launch suite with ${compilerVersion}`,
);

for (
  const contractName of
  CONTRACT_NAMES
) {
  const bytecode =
    artifacts[
      contractName
    ].bytecode;

  console.log(
    `${contractName}: ${
      (bytecode.length - 2) /
      2
    } bytes`,
  );
}

console.log(
  `Verification sources: ${
    Object.keys(sources)
      .length
  }`,
);
