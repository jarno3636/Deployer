import fs from 'node:fs';
import path from 'node:path';
import solc from 'solc';

const root = process.cwd();
const contractPath = path.join(root, 'contracts', 'TobyworldMarketplaceV1.sol');
const source = fs.readFileSync(contractPath, 'utf8');

const input = {
  language: 'Solidity',
  sources: {
    'contracts/TobyworldMarketplaceV1.sol': { content: source },
  },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    outputSelection: {
      '*': {
        '*': ['abi', 'evm.bytecode.object', 'metadata'],
      },
    },
  },
};

function findImports(importPath) {
  const candidates = [
    path.join(root, importPath),
    path.join(root, 'node_modules', importPath),
  ];
  for (const candidate of candidates) {
    if (fs.existsSync(candidate)) {
      return { contents: fs.readFileSync(candidate, 'utf8') };
    }
  }
  return { error: `Import not found: ${importPath}` };
}

const output = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
const errors = (output.errors ?? []).filter((e) => e.severity === 'error');
if (errors.length) {
  console.error(errors.map((e) => e.formattedMessage).join('\n'));
  process.exit(1);
}

const artifact = output.contracts['contracts/TobyworldMarketplaceV1.sol'].TobyworldMarketplaceV1;
const bytecode = `0x${artifact.evm.bytecode.object}`;
if (bytecode === '0x') throw new Error('Compiled bytecode is empty.');

const generated = `// AUTO-GENERATED by scripts/compile-contract.mjs. Do not edit.\nexport const marketplaceAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\nexport const marketplaceBytecode = ${JSON.stringify(bytecode)} as const;\nexport const compilerVersion = ${JSON.stringify(solc.version())} as const;\n`;
fs.writeFileSync(path.join(root, 'lib', 'marketplace.generated.ts'), generated);
console.log(`Compiled TobyworldMarketplaceV1 with ${solc.version()}`);
console.log(`Creation bytecode: ${(bytecode.length - 2) / 2} bytes`);
