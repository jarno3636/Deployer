import fs from 'node:fs';
import path from 'node:path';
import solc from 'solc';

const root = process.cwd();
const entryUnit = 'contracts/TobyworldMarketplaceV1.sol';
const entryPath = path.join(root, entryUnit);

function fileForUnit(unit) {
  if (unit.startsWith('@')) return path.join(root, 'node_modules', unit);
  return path.join(root, unit);
}

function normalizeUnit(parentUnit, imported) {
  if (imported.startsWith('.')) {
    return path.posix.normalize(path.posix.join(path.posix.dirname(parentUnit), imported));
  }
  return imported;
}

function extractImports(source) {
  const imports = [];
  const re = /import\s+(?:(?:[^'\"]*?\s+from\s+)?)[\"']([^\"']+)[\"']\s*;/g;
  let match;
  while ((match = re.exec(source)) !== null) imports.push(match[1]);
  return imports;
}

const sources = {};
const visiting = new Set();

function addSource(unit) {
  if (sources[unit] || visiting.has(unit)) return;
  visiting.add(unit);

  const file = fileForUnit(unit);
  if (!fs.existsSync(file)) throw new Error(`Import not found while building verification input: ${unit}`);

  const content = fs.readFileSync(file, 'utf8');
  sources[unit] = { content };

  for (const imported of extractImports(content)) {
    addSource(normalizeUnit(unit, imported));
  }

  visiting.delete(unit);
}

addSource(entryUnit);

const input = {
  language: 'Solidity',
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    outputSelection: {
      '*': {
        '*': ['abi', 'evm.bytecode.object', 'metadata'],
      },
    },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors ?? []).filter((e) => e.severity === 'error');
if (errors.length) {
  console.error(errors.map((e) => e.formattedMessage).join('\n'));
  process.exit(1);
}

const artifact = output.contracts[entryUnit].TobyworldMarketplaceV1;
const bytecode = `0x${artifact.evm.bytecode.object}`;
if (bytecode === '0x') throw new Error('Compiled bytecode is empty.');

const rawCompilerVersion = solc.version();
const compilerVersion = rawCompilerVersion.replace(/\.Emscripten\.clang$/, '');
const etherscanCompilerVersion = `v${compilerVersion}`;
const standardJsonInput = JSON.stringify(input);

const generated = `// AUTO-GENERATED by scripts/compile-contract.mjs. Do not edit.\nexport const marketplaceAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\nexport const marketplaceBytecode = ${JSON.stringify(bytecode)} as const;\nexport const compilerVersion = ${JSON.stringify(rawCompilerVersion)} as const;\n`;

const verificationGenerated = `// AUTO-GENERATED by scripts/compile-contract.mjs. Server-side only. Do not edit.\nexport const marketplaceStandardJsonInput = ${JSON.stringify(standardJsonInput)} as const;\nexport const etherscanCompilerVersion = ${JSON.stringify(etherscanCompilerVersion)} as const;\nexport const etherscanContractName = ${JSON.stringify(`${entryUnit}:TobyworldMarketplaceV1`)} as const;\n`;

fs.writeFileSync(path.join(root, 'lib', 'marketplace.generated.ts'), generated);
fs.writeFileSync(path.join(root, 'lib', 'marketplace.verification.generated.ts'), verificationGenerated);

console.log(`Compiled TobyworldMarketplaceV1 with ${rawCompilerVersion}`);
console.log(`Creation bytecode: ${(bytecode.length - 2) / 2} bytes`);
console.log(`Verification sources: ${Object.keys(sources).length}`);
