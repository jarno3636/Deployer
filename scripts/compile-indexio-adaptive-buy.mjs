import fs from 'node:fs';
import path from 'node:path';
import solc from 'solc';
import {keccak256} from 'viem';

// Standalone release: never change V3.3.8 creation-bytecode artifacts.
const root=process.cwd();
const entries=[
  'contracts/indexio-v3/IndexioProportionalBuyRouterV338.sol',
  'contracts/indexio-v3/IndexioRestrictedSwapAdapterV3.sol',
  'contracts/indexio-v3/IndexioLifiSwapAdapterV3.sol',
];
const imports=/import\s+(?:[^"']*?from\s+)?["']([^"']+)["']\s*;/g;
const sources={};
function resolve(from,ref){
  if(ref.startsWith('@'))return ref;
  return ref.startsWith('.')?path.posix.normalize(path.posix.join(path.posix.dirname(from),ref)):ref;
}
function add(file){
  if(sources[file])return;
  const local=file.startsWith('@openzeppelin/')?path.join(root,'node_modules',file):path.join(root,file);
  if(!fs.existsSync(local))throw Error(`Missing Solidity dependency ${file}. Run npm ci.`);
  const content=fs.readFileSync(local,'utf8');
  sources[file]={content};
  for(const match of content.matchAll(imports))add(resolve(file,match[1]));
}
for(const file of entries)add(file);
const input={language:'Solidity',sources,settings:{optimizer:{enabled:true,runs:500},viaIR:true,outputSelection:{'*':{'*':['abi','evm.bytecode.object','evm.deployedBytecode.object','metadata']}}}};
const output=JSON.parse(solc.compile(JSON.stringify(input)));
for(const diagnostic of output.errors||[]) (diagnostic.severity==='error'?console.error:console.warn)(diagnostic.formattedMessage||diagnostic.message);
if((output.errors||[]).some(e=>e.severity==='error'))process.exit(1);
const contracts={
  router:['contracts/indexio-v3/IndexioProportionalBuyRouterV338.sol','IndexioProportionalBuyRouterV338'],
  zeroX:['contracts/indexio-v3/IndexioRestrictedSwapAdapterV3.sol','IndexioRestrictedSwapAdapterV3'],
  lifi:['contracts/indexio-v3/IndexioLifiSwapAdapterV3.sol','IndexioLifiSwapAdapterV3'],
};
const a={};let failed=false;
for(const [key,[source,name]] of Object.entries(contracts)){
  const c=output.contracts?.[source]?.[name];if(!c)throw Error(`Missing ${source}:${name}`);
  a[key]={abi:c.abi,bytecode:`0x${c.evm.bytecode.object}`,creationBytes:c.evm.bytecode.object.length/2,runtimeBytes:c.evm.deployedBytecode.object.length/2,creationCodeHash:keccak256(`0x${c.evm.bytecode.object}`)};
  console.log(`${key}: creation ${a[key].creationBytes} bytes; runtime ${a[key].runtimeBytes} bytes`);
  if(a[key].runtimeBytes>24576||a[key].creationBytes>49152){console.error(`${key} exceeds Base EVM code-size limits`);failed=true;}
}
if(failed)process.exit(1);
let source='// AUTOGENERATED after npm run compile:indexio-adaptive-buy. Do not edit.\n';
for(const [key,record] of Object.entries(a)){
  const title=key==='zeroX'?'ZeroX':key[0].toUpperCase()+key.slice(1);
  source+=`export const adaptiveBuy${title}Abi=${JSON.stringify(record.abi)} as const;\n`;
  source+=`export const adaptiveBuy${title}Bytecode=${JSON.stringify(record.bytecode)} as \`0x\${string}\`;\n`;
  source+=`export const adaptiveBuy${title}CodeHash=${JSON.stringify(record.creationCodeHash)} as \`0x\${string}\`;\n`;
}
fs.writeFileSync(path.join(root,'lib/indexio-adaptive-buy.generated.ts'),source);
fs.mkdirSync(path.join(root,'artifacts'),{recursive:true});
fs.writeFileSync(path.join(root,'artifacts/indexio-adaptive-buy-standard-json-input.json'),JSON.stringify(input));
fs.writeFileSync(path.join(root,'artifacts/indexio-adaptive-buy-artifacts.json'),JSON.stringify({release:'Indexio V3.3.8 adaptive-buy candidate',compiler:solc.version(),contracts:a},null,2));
fs.writeFileSync(path.join(root,'lib/indexio-adaptive-buy-verification.generated.ts'),`// GENERATED Indexio adaptive-buy Etherscan standard JSON\nexport const adaptiveBuyStandardJsonInput=${JSON.stringify(JSON.stringify(input))} as const;\n`);
console.log('Adaptive buy artifacts generated; main V3.3.8 suite artifacts unchanged.');
