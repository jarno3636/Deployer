import fs from 'node:fs';
import path from 'node:path';
import solc from 'solc';

const root = process.cwd();
const entry = 'contracts/indexio/IndexioRestrictedSwapAdapter.sol';
const importPattern = /import\s+(?:[^"']*?from\s+)?["']([^"']+)["']\s*;/g;
const sources = {};

function resolveImport(fromKey, request) {
  if (request.startsWith('@')) return request;
  if (request.startsWith('.')) return path.posix.normalize(path.posix.join(path.posix.dirname(fromKey), request));
  return request;
}
function diskPathFor(sourceKey) {
  if (sourceKey.startsWith('@openzeppelin/')) return path.join(root, 'node_modules', sourceKey);
  return path.join(root, sourceKey);
}
function addSource(sourceKey) {
  if (sources[sourceKey]) return;
  const diskPath = diskPathFor(sourceKey);
  if (!fs.existsSync(diskPath)) throw new Error(`Adapter compiler could not resolve ${sourceKey} at ${diskPath}`);
  const content = fs.readFileSync(diskPath, 'utf8');
  sources[sourceKey] = { content };
  for (const match of content.matchAll(importPattern)) addSource(resolveImport(sourceKey, match[1]));
}
addSource(entry);

const input = {
  language: 'Solidity',
  sources,
  settings: {
    optimizer: { enabled: true, runs: 500 },
    viaIR: true,
    outputSelection: {
      '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object', 'metadata'] },
    },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));
const diagnostics = output.errors || [];
for (const d of diagnostics) {
  const line = d.formattedMessage || d.message;
  if (d.severity === 'error') console.error(line); else console.warn(line);
}
if (diagnostics.some((d) => d.severity === 'error')) process.exit(1);

const contract = output.contracts?.[entry]?.IndexioRestrictedSwapAdapter;
if (!contract?.abi || !contract?.evm?.bytecode?.object || !contract?.evm?.deployedBytecode?.object) {
  throw new Error('Missing IndexioRestrictedSwapAdapter compiler output.');
}

const bytecode = `0x${contract.evm.bytecode.object}`;
const creationBytes = contract.evm.bytecode.object.length / 2;
const runtimeBytes = contract.evm.deployedBytecode.object.length / 2;
const compilerVersion = solc.version();

if (runtimeBytes > 24_576) throw new Error(`IndexioRestrictedSwapAdapter runtime ${runtimeBytes} exceeds EIP-170 limit.`);
if (creationBytes > 49_152) throw new Error(`IndexioRestrictedSwapAdapter init code ${creationBytes} exceeds EIP-3860 limit.`);

const generated = `// AUTO-GENERATED by scripts/compile-indexio-adapter.mjs. Do not edit.\n` +
  `export const indexioAdapterCompilerVersion = ${JSON.stringify(compilerVersion)} as const;\n` +
  `export const indexioRestrictedSwapAdapterAbi = ${JSON.stringify(contract.abi)} as const;\n` +
  `export const indexioRestrictedSwapAdapterBytecode = ${JSON.stringify(bytecode)} as \`0x\${string}\`;\n` +
  `export const indexioRestrictedSwapAdapterCreationBytes = ${creationBytes} as const;\n` +
  `export const indexioRestrictedSwapAdapterRuntimeBytes = ${runtimeBytes} as const;\n`;

const verification = `// AUTO-GENERATED by scripts/compile-indexio-adapter.mjs. Do not edit.\n` +
  `export const indexioAdapterStandardJsonInput = ${JSON.stringify(JSON.stringify(input))} as const;\n`;

fs.mkdirSync(path.join(root, 'lib'), { recursive: true });
fs.writeFileSync(path.join(root, 'lib', 'indexio-adapter.generated.ts'), generated);
fs.writeFileSync(path.join(root, 'lib', 'indexio-adapter-verification.generated.ts'), verification);
console.log(`IndexioRestrictedSwapAdapter: ${creationBytes} creation bytes; ${runtimeBytes} runtime bytes; ${compilerVersion}`);
